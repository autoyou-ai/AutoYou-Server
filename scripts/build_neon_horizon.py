"""Keep the standalone phone download in sync with Game Studio's Horizon page.

Run after editing play.html. Both deliverables remain self-contained, so the
phone needs no network or bundled JavaScript loader to play the downloaded game.
"""

from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "autoyou_agents/game_agent/website/frontend/play.html"
OUTPUT = ROOT / "assets/game/neon-horizon.html"
CSP = (
    '<meta http-equiv="Content-Security-Policy" content="default-src \'none\'; '
    "script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data:; "
    'media-src data:; connect-src \'none\'">'
)


def render_mobile(html: str) -> str:
    return html.replace(
        "<head>", "<head>\n  <!-- Generated by scripts/build_neon_horizon.py. Edit Game Studio play.html. -->\n  " + CSP, 1
    ).replace("<body>", "<body data-offline>", 1).replace(
        "Neon Horizon - Game Studio", "Neon Horizon - AutoYou", 1
    )


if __name__ == "__main__":
    OUTPUT.write_text(render_mobile(SOURCE.read_text(encoding="utf-8")), encoding="utf-8", newline="\n")
    print(f"Updated {OUTPUT.relative_to(ROOT)}")
